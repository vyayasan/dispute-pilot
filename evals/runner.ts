import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { DEFAULT_POLICY, decide } from "../src/policy/policy.js";
import { ceFootprintCheck } from "../src/evidence/assemble.js";
import { ce3Checks } from "./ce3.js";
import { scenarios, evalNow } from "./scenarios.js";
import { govScenarios, runGov } from "./governance.js";

const rows = scenarios.map((scenario) => {
  let actual: string;
  let error: string | undefined;
  try {
    actual = decide(scenario.dispute, scenario.facts, scenario.evidence, DEFAULT_POLICY, evalNow).action;
  } catch (cause) {
    actual = "THREW";
    error = cause instanceof Error ? cause.message : String(cause);
  }
  return { ...scenario, actual, pass: actual === scenario.expected, error };
});
const ceRows = ce3Checks.map((check) => {
  const result = ceFootprintCheck(check.orders, check.disputed);
  return { ...check, actual: result.ok, matched: result.matched, pass: result.ok === check.expected };
});
const govRows = govScenarios.map((s) => ({ ...s, ...runGov(s) }));
const allRows = [...rows, ...ceRows, ...govRows.map((g) => ({ ...g, actual: g.gate?.finalAction ?? "n/a", matched: [] as string[] }))] as typeof rows;
const pass = allRows.filter((row) => row.pass).length;
const failures = allRows.filter((row) => !row.pass);
const security = rows.filter((row) => row.securityExpectation);
const securityFailures = security.filter((row) => !row.pass);
const rate = (n: number, d: number) => `${n}/${d} (${d ? (100 * n / d).toFixed(1) : "0.0"}%)`;
const lines = [
  "# Dispute policy eval results", "",
  "Regenerated by `npm run evals`. Deterministic fixed evaluation time: `2026-10-20T12:00:00.000Z`. No network or secrets.", "",
  "## Summary scorecard", "",
  `- Combined: **${rate(pass, allRows.length)} passed** (${rows.length} policy scenarios + ${ceRows.length} CE 3.0 implementation checks + ${govRows.length} model governance scenarios)`,
  `- Policy scenarios: **${rate(rows.filter((row) => row.pass).length, rows.length)} passed**`,
  `- CE 3.0 helper checks: **${rate(ceRows.filter((row) => row.pass).length, ceRows.length)} passed**`,
  `- Model governance scenarios: **${rate(govRows.filter((g) => g.pass).length, govRows.length)} passed**
- Fail-closed/security expectations: **${rate(security.length - securityFailures.length, security.length)} passed** (${securityFailures.length} gap(s))`,
  `- Policy: ${DEFAULT_POLICY.version}; fixed clock used for all policy scenarios.`, "",
  "A failed scenario means current behavior differs from the intended safe outcome. Failures are reported as policy gaps, not normalized away.", "",
  "## Policy scenario results", "",
  "| Result | Scenario | Family | Expected | Actual | Why |", "|---|---|---|---|---|---|",
  ...rows.map((row) => `| ${row.pass ? "PASS" : "FAIL"} | \`${row.id}\` | ${row.family.replaceAll("|", "\\|")} | ${row.expected} | ${row.actual}${row.error ? ` (${row.error})` : ""} | ${row.why.replaceAll("|", "\\|")} |`),
  "", "## CE 3.0 footprint helper checks", "",
  "| Result | Check | Expected valid | Actual valid | Matched qualifying orders | Why |", "|---|---|---:|---:|---|---|",
  ...ceRows.map((row) => `| ${row.pass ? "PASS" : "FAIL"} | \`${row.id}\` | ${row.expected} | ${row.actual} | ${row.matched.join(", ") || "none"} | ${row.why} |`),
  "", "## Model governance scenarios", "",
  "Scripted model proposals through guardrails, rubric, reasoning checks and the policy gate. No model is called.", "",
  "| Result | Scenario | Family | Expected | Actual | Layer said | Why |", "|---|---|---|---|---|---|---|",
  ...govRows.map((g) => `| ${g.pass ? "PASS" : "FAIL"} | \`${g.id}\` | ${g.family} | ${g.expectAccepted ? "accepted" : "rejected"} / ${g.expectAction} | ${g.gate ? (g.gate.accepted ? "accepted" : "rejected") + " / " + g.gate.finalAction : "n/a"} | ${(g.gate?.reasons[0] ?? g.error ?? "").replaceAll("|", "\\|").slice(0, 110)} | ${g.why} |`),
  "", "## Gaps to address", "",
  ...(failures.length ? failures.map((row) => `- **${row.id}**: expected ${"expected" in row ? row.expected : "n/a"}, got ${row.actual}. ${row.why}`) : ["- None in this run."]),
  "", "## Interpretation", "",
  "The engine currently has special scoring only for Visa 10.4 and 13.1. Other Visa/Mastercard labels exercise conservative baseline behavior and do not assert full scheme rule implementation. Fee and autonomy-cap values are not FX-converted, so multi-currency cases reveal nominal policy behavior, not economically normalized equivalents. The policy lacks an explicit mandate-validation input; upstream code must not rely on generic evidence presence to establish a valid mandate.",
  "", "Passes are synthetic deterministic checks, not scheme certification, issuer outcome guarantees, or legal advice.", "",
];
writeFileSync(fileURLToPath(new URL("./RESULTS.md", import.meta.url)), lines.join("\n"));
console.log("Dispute Pilot policy evals (deterministic; no network)\n");
for (const row of rows) console.log(`${row.pass ? "PASS" : "FAIL"} ${row.id}: expected ${row.expected}, got ${row.actual}${row.error ? ` (${row.error})` : ""}`);
for (const row of ceRows) console.log(`${row.pass ? "PASS" : "FAIL"} ${row.id}: expected valid=${row.expected}, got ${row.actual}; matched=${row.matched.join(",") || "none"}`);
console.log(`\nScorecard: ${rate(pass, allRows.length)} overall (${rate(rows.filter((row) => row.pass).length, rows.length)} policy; ${rate(ceRows.filter((row) => row.pass).length, ceRows.length)} CE 3.0).`);
for (const family of [...new Set(rows.map((row) => row.family.split(" /")[0]))]) {
  const members = rows.filter((row) => row.family.startsWith(family));
  console.log(`  ${family}: ${rate(members.filter((row) => row.pass).length, members.length)}`);
}
console.log("\nWrote evals/RESULTS.md");
if (securityFailures.length) console.log("SECURITY GAP: invalid inputs or unverified mandate evidence are not consistently rejected before policy evaluation.");
if (failures.length) process.exitCode = 1;
